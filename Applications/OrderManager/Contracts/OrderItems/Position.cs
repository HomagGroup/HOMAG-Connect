using HomagConnect.Base.Contracts.Attributes;
using HomagConnect.Base.Contracts.Enumerations;
using HomagConnect.OrderManager.Contracts.Interfaces;
using Newtonsoft.Json;
using System.Collections.ObjectModel;
using System.ComponentModel;
using System.ComponentModel.DataAnnotations;

// Note: This is preliminary code and is subject to change

namespace HomagConnect.OrderManager.Contracts.OrderItems;

/// <summary>
/// Position of an order, for example a configured article with its dimensions and attributes.
/// </summary>
/// <example>
/// { "type": "Position", "id": "P1", "name": "Base cabinet", "positionNumber": "1", "articleNumber": "UK-60", "state": "New", "quantity": 2, "height": 720, "width": 600, "depth": 560, "color": "Oak", "procurementType": "MTO", "positionType": "Standard" }
/// </example>
public class Position : Base, IArticle
{
    /// <summary>
    /// Name of the position. Optional.
    /// </summary>
    /// <example>Base cabinet</example>
    [JsonProperty(Order = 1)]
    public string? Name { get; set; }

    /// <inheritdoc />
    public override Type Type
    {
        get
        {
            return Type.Position;
        }
        set
        {
            // Ignore
        }
    }

    /// <summary>
    /// Position number, which must be unique within an order and is shown wherever the position is referenced.
    /// If not set, it can be generated by the system. Optional.
    /// </summary>
    /// <example>1</example>
    [JsonProperty(Order = 1)]
    [StringLength(100)]
    public string? PositionNumber { get; set; }

    /// <summary>
    /// <c>true</c> if the position is hidden. A hidden position is never shown in the order overview or printed documents. Optional.
    /// </summary>
    /// <example>false</example>
    [JsonProperty(Order = 10)]
    public bool? IsHidden { get; set; }

    /// <inheritdoc />
    [JsonProperty(Order = 2)]
    [StringLength(100)]
    public string? ArticleNumber { get; set; }

    /// <inheritdoc />
    [JsonProperty(Order = 2)]
    [StringLength(100)]
    public string? ArticleName { get; set; }

    /// <inheritdoc />
    [JsonProperty(Order = 2)]
    public string? ArticleCategory { get; set; }

    /// <inheritdoc />
    [JsonProperty(Order = 3)]
    [StringLength(1000)]
    public string? Description { get; set; }

    /// <summary>
    /// Catalog the article belongs to. Optional.
    /// </summary>
    /// <example>Kitchen 2025</example>
    [JsonProperty(Order = 3)]
    public string? Catalog { get; set; }

    /// <summary>
    /// Quantity of the position. Defaults to 1.
    /// </summary>
    /// <example>2</example>
    [JsonProperty(Order = 4)]
    [Range(0, int.MaxValue)]
    public int Quantity { get; set; } = 1;

    /// <summary>
    /// Height of the position. Optional.
    /// </summary>
    /// <example>720</example>
    [JsonProperty(Order = 5)]
    [Range(0.1, 9999.9)]
    [ValueDependsOnUnitSystem(BaseUnit.Millimeter)]
    public double? Height { get; set; }

    /// <summary>
    /// Width of the position. Optional.
    /// </summary>
    /// <example>600</example>
    [JsonProperty(Order = 6)]
    [Range(0.1, 9999.9)]
    [ValueDependsOnUnitSystem(BaseUnit.Millimeter)]
    public double? Width { get; set; }

    /// <summary>
    /// Depth of the position. Optional.
    /// </summary>
    /// <example>560</example>
    [JsonProperty(Order = 7)]
    [Range(0.1, 9999.9)]
    [ValueDependsOnUnitSystem(BaseUnit.Millimeter)]
    public double? Depth { get; set; }

    /// <summary>
    /// Color of the position. Optional.
    /// </summary>
    /// <example>Oak</example>
    [JsonProperty(Order = 8)]
    [StringLength(100)]
    public string? Color { get; set; }

    /// <summary>
    /// Carcase color of the position. Optional.
    /// </summary>
    /// <example>White</example>
    [JsonProperty(Order = 8)]
    [StringLength(100)]
    public string? CarcaseColor { get; set; }

    /// <summary>
    /// Door direction of the position. Optional.
    /// </summary>
    /// <example>Left</example>
    [JsonProperty(Order = 8)]
    [StringLength(100)]
    public string? DoorDirection { get; set; }

    /// <summary>
    /// Procurement type. Optional. Values:
    /// <list type="bullet">
    /// <item><description><c>PTO</c> - purchase to order</description></item>
    /// <item><description><c>MTO</c> - make to order</description></item>
    /// <item><description><c>MTS</c> - make to stock</description></item>
    /// </list>
    /// </summary>
    /// <example>MTO</example>
    [JsonProperty(Order = 9)]
    [StringLength(100)]
    public string? ProcurementType { get; set; }

    /// <summary>
    /// Type of the position. Optional. Treated as <see cref="OrderItems.PositionType.Standard" /> if not specified.
    /// </summary>
    /// <example>Standard</example>
    [JsonProperty(Order = 10)]
    public PositionType? PositionType { get; set; }

    /// <summary>
    /// State of the position. Defaults to <c>New</c>.
    /// </summary>
    /// <example>New</example>
    [JsonProperty(Order = 2)]
    [DefaultValue(State.New)]
    public State State { get; set; } = State.New;

    /// <summary>
    /// Configuration and other attribute information that can be displayed under the position. Optional.
    /// </summary>
    [JsonProperty(Order = 50)]
    public Collection<ConfigurationAttribute>? Attributes { get; set; } = new Collection<ConfigurationAttribute>();
}
